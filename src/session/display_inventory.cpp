    std::string_view trim(std::string_view value) {
      constexpr std::string_view whitespace = " \t\r\n";
      const auto first = value.find_first_not_of(whitespace);
      if (first == std::string_view::npos) return {};
      const auto last = value.find_last_not_of(whitespace);
      return value.substr(first, last - first + 1);
    }

    std::vector<std::string_view> split_lines(std::string_view text) {
      std::vector<std::string_view> lines;
      std::size_t start = 0;
      while (start <= text.size()) {
        const auto end = text.find('\n', start);
        lines.push_back(text.substr(start, (end == std::string_view::npos ? text.size() : end) - start));
        if (end == std::string_view::npos) break;
        start = end + 1;
      }
      return lines;
    }

    std::vector<std::string_view> split_words(std::string_view text) {
      std::vector<std::string_view> words;
      std::size_t cursor = 0;
      while (cursor < text.size()) {
        const auto start = text.find_first_not_of(" \t", cursor);
        if (start == std::string_view::npos) break;
        const auto end = text.find_first_of(" \t", start);
        words.push_back(text.substr(start, (end == std::string_view::npos ? text.size() : end) - start));
        cursor = end == std::string_view::npos ? text.size() : end;
      }
      return words;
    }

    template<class Integer>
    std::optional<Integer> parse_integer(std::string_view value) {
      Integer result {};
      const auto parsed = std::from_chars(value.data(), value.data() + value.size(), result);
      if (value.empty() || parsed.ec != std::errc {} || parsed.ptr != value.data() + value.size()) {
        return std::nullopt;
      }
      return result;
    }

    /** `152.840MHz` -> 152840 (kHz). */
    std::optional<std::int64_t> parse_clock_khz(std::string_view token) {
      if (!token.ends_with("MHz")) return std::nullopt;
      token.remove_suffix(3);
      const auto dot = token.find('.');
      const auto whole = parse_integer<std::int64_t>(token.substr(0, dot));
      if (!whole) return std::nullopt;
      std::int64_t fraction = 0;
      if (dot != std::string_view::npos) {
        auto digits = std::string {token.substr(dot + 1)};
        if (digits.empty() || digits.size() > 3) return std::nullopt;
        digits.resize(3, '0');
        const auto parsed = parse_integer<std::int64_t>(digits);
        if (!parsed) return std::nullopt;
        fraction = *parsed;
      }
      return *whole * 1000 + fraction;
    }

    bool name_token(std::string_view value, std::string_view prefix) {
      if (!value.starts_with(prefix) || value.size() == prefix.size()) return false;
      return std::all_of(value.begin() + static_cast<std::ptrdiff_t>(prefix.size()), value.end(),
                         [](char c) { return c >= '0' && c <= '9'; });
    }

    int device_number(const display_device_t &device) {
      const auto number = parse_integer<int>(std::string_view {device.dfp}.substr(4));
      return number.value_or(1 << 20);
    }

    bool safe_name(std::string_view value) {
      return !value.empty() && value.size() <= 32 &&
             std::all_of(value.begin(), value.end(), [](char c) {
               return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') ||
                      (c >= '0' && c <= '9') || c == '-' || c == '_';
             });
    }

    bool display_name_character(char c) {
      return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') ||
             c == ' ' || c == '.' || c == '_' || c == '(' || c == ')' || c == '+' ||
             c == '-' || c == '/';
    }

    std::string sanitize_display_name(std::string_view value) {
      std::string result;
      for (const char c : trim(value)) {
        if (result.size() >= maximum_display_name) break;
        result.push_back(display_name_character(c) ? c : '_');
      }
      return std::string {trim(result)};
    }

    bool valid_display_name(std::string_view value) {
      return value.size() <= maximum_display_name &&
             std::all_of(value.begin(), value.end(), display_name_character) &&
             trim(value).size() == value.size();
    }

    bool lower_hex(std::string_view value, std::size_t size) {
      return value.size() == size && std::all_of(value.begin(), value.end(), [](char c) {
               return (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f');
             });
    }

    bool valid_bus_id(std::string_view value) {
      // PCI:bus[@domain]:device:function, decimal.
      if (!value.starts_with("PCI:") || value.size() > 32) return false;
      auto rest = value.substr(4);
      int fields = 0;
      while (!rest.empty()) {
        const auto colon = rest.find(':');
        auto field = rest.substr(0, colon);
        if (fields == 0) {
          const auto at = field.find('@');
          if (at != std::string_view::npos) {
            if (!parse_integer<unsigned>(field.substr(at + 1))) return false;
            field = field.substr(0, at);
          }
        }
        if (!parse_integer<unsigned>(field)) return false;
        ++fields;
        if (colon == std::string_view::npos) break;
        rest = rest.substr(colon + 1);
        if (rest.empty()) return false;
      }
      return fields == 3;
    }

    bool valid_driver_version(std::string_view value) {
      return !value.empty() && value.size() <= 32 &&
             std::all_of(value.begin(), value.end(), [](char c) {
               return (c >= '0' && c <= '9') || c == '.';
             });
    }

    bool valid_mode_list(std::string_view value) {
      if (value.empty()) return true;
      std::size_t start = 0;
      while (true) {
        const auto comma = value.find(',', start);
        if (!plank::arrangement::parse_mode_name(value.substr(start, comma - start))) return false;
        if (comma == std::string_view::npos) return true;
        start = comma + 1;
      }
    }

    std::vector<std::string> split_modes(std::string_view value) {
      std::vector<std::string> modes;
      if (value.empty()) return modes;
      std::size_t start = 0;
      while (true) {
        const auto comma = value.find(',', start);
        modes.emplace_back(value.substr(start, comma - start));
        if (comma == std::string_view::npos) return modes;
        start = comma + 1;
      }
    }

    std::string join_modes(const std::vector<std::string> &modes) {
      std::string result;
      for (const auto &mode : modes) {
        if (!result.empty()) result += ',';
        result += mode;
      }
      return result;
    }

    std::string inventory_fingerprint(const inventory_t &inventory) {
      std::string text = "plank-display-inventory-1\n" + inventory.gpu_bus_id + "\n" +
                         inventory.driver_version + "\n";
      for (const auto &output : inventory.physical) {
        text += "P " + output.device.dfp + " " + output.device.dpy + " " + output.device.randr +
                " " + output.device.connector + " " + output.edid_sha256 + "\n";
      }
      for (const auto &output : inventory.virtual_candidates) {
        text += "V " + output.device.dfp + " " + output.device.dpy + " " + output.device.randr +
                " " + output.device.connector + "\n";
      }
      return sha256_hex(text);
    }

